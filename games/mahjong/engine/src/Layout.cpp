Layout parseLayout(std::string name, int difficulty, const std::vector<std::vector<std::string>>& layers)
{
    Layout layout;
    layout.name = std::move(name);
    layout.difficulty = difficulty;
    layout.layers = int(layers.size());
    for (int z = 0; z < int(layers.size()); ++z) {
        for (int row = 0; row < int(layers[z].size()); ++row) {
            const std::string& line = layers[z][row];
            for (int col = 0; col < int(line.size()); ++col) {
                const char c = line[col];
                if (c != '#' && c != '>' && c != 'v' && c != '+')
                    continue;
                Slot slot { 2 * col + (c == '>' || c == '+'), 2 * row + (c == 'v' || c == '+'), z };
                layout.places.push_back(slot);
                layout.width = std::max(layout.width, slot.x + 2);
                layout.height = std::max(layout.height, slot.y + 2);
            }
        }
    }
    return layout;
}

